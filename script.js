const losingWords = [

    "예시패배단어"

]


// ========================================
// 게임 설정
// ========================================

const startLetters = [
    "기", "시", "이", "비", "미", "아",
    "가", "다", "바", "마", "사", "수",
    "구", "두", "주", "지", "자", "보",
    "부", "모", "무", "소", "고", "도",
    "우", "오", "의", "하", "차", "호"
];

let currentWord = "";
let usedWords = [];
let lives = 2;
let timer = 20;
let timerInterval = null;
let playerTurn = false;
let firstMove = true;


// ========================================
// 모든 단어 합치기
// ========================================

const allWords = [
    ...oneShotWords,
    ...attackWords,
    ...lootWords,
    ...losingWords
];


// ========================================
// 게임 시작
// ========================================

function startGame(mode) {

    document.getElementById("startScreen").classList.add("hidden");
    document.getElementById("gameScreen").classList.remove("hidden");

    lives = 2;
    usedWords = [];
    firstMove = true;

    // 시작 글자 랜덤 선택
    const randomIndex =
        Math.floor(Math.random() * startLetters.length);

    currentWord = startLetters[randomIndex];

    document.getElementById("currentWord").textContent = currentWord;

    // 선공 / 후공 / 랜덤 결정
    if (mode === "first") {
        playerTurn = true;
    }

    else if (mode === "second") {
        playerTurn = false;
    }

    else {
        playerTurn = Math.random() < 0.5;
    }

    updateLives();
    updateNextLetter();

    if (playerTurn) {
        showMessage("당신의 차례입니다.");
        startTimer();
    }

    else {
        showMessage("봇이 생각 중...");
        startTimer();
        setTimeout(botTurn, 1000);
    }
}


// ========================================
// 단어 입력
// ========================================

function submitWord() {

    if (!playerTurn) {
        return;
    }

    const input = document.getElementById("wordInput");
    const word = input.value.trim();

    input.value = "";

    if (word === "") {
        return;
    }

    // 이미 사용한 단어
    if (usedWords.includes(word)) {
        showMessage("이미 사용한 단어입니다.");
        return;
    }

    // 존재하지 않는 단어
    if (!allWords.includes(word)) {
        showMessage("존재하지 않는 단어입니다.");
        return;
    }

    // 첫 글자 확인
    const requiredLetter = getRequiredLetter(currentWord);

    if (word.charAt(0) !== requiredLetter) {
        showMessage("단어의 첫 글자가 맞지 않습니다.");
        return;
    }

    // 첫 번째 수에는 한방단어/공격단어 사용 불가
    if (firstMove) {
        if (
            oneShotWords.includes(word) ||
            attackWords.includes(word)
        ) {
            showMessage("처음에 사용할 수 없는 단어입니다.");
            return;
        }
    }

    // 정상 입력
    stopTimer();

    currentWord = word;
    usedWords.push(word);

    firstMove = false;

    addWordToHistory(word);

    document.getElementById("currentWord").textContent =
        currentWord;

    updateNextLetter();

    playerTurn = false;

    showMessage("봇이 생각 중...");

    setTimeout(botTurn, 800);
}


// ========================================
// 봇 차례
// ========================================

function botTurn() {

    if (lives <= 0) {
        return;
    }

    const requiredLetter =
        getRequiredLetter(currentWord);


    // 봇이 낼 수 있는 단어 찾기
const possibleWords = allWords.filter(word => {

    // 현재 글자로 시작해야 함
    if (word.charAt(0) !== requiredLetter) {
        return false;
    }

    // 이미 사용한 단어는 사용 불가
    if (usedWords.includes(word)) {
        return false;
    }

    // 첫 번째 단어에서는 한방단어와 공격단어 사용 불가
    if (
        firstMove &&
        (
            oneShotWords.includes(word) ||
            attackWords.includes(word)
        )
    ) {
        return false;
    }

    return true;
});


    // ----------------------------------------
    // 봇이 낼 단어가 없음
    // ----------------------------------------

    if (possibleWords.length === 0) {

        showMessage("봇이 더 이상 낼 단어가 없습니다!");

        endGame(true);

        return;
    }


    // 랜덤으로 선택
    const randomIndex =
        Math.floor(Math.random() * possibleWords.length);

    const botWord =
        possibleWords[randomIndex];


    currentWord = botWords

    usedWords.push(botWord);

    firstMove = false;

    addWordToHistory(botWord);

    document.getElementById("currentWord").textContent =
        currentWord;

    updateNextLetter();

    showMessage("봇: " + botWord);

    playerTurn = true;

    startTimer();
}


// ========================================
// 다음 글자 계산
// ========================================

function getRequiredLetter(word) {

    return word.charAt(word.length - 1);
}


// ========================================
// 제한시간 시작
// ========================================

function startTimer() {

    stopTimer();

    timer = 20;

    document.getElementById("timer").textContent =
        timer;

    timerInterval = setInterval(() => {

        timer--;

        document.getElementById("timer").textContent =
            timer;

        if (timer <= 0) {

            stopTimer();

            timeOut();
        }

    }, 1000);
}


// ========================================
// 제한시간 종료
// ========================================

function stopTimer() {

    if (timerInterval !== null) {

        clearInterval(timerInterval);

        timerInterval = null;
    }
}


// ========================================
// 시간 초과
// ========================================

function timeOut() {

    if (!playerTurn) {
        return;
    }

    lives--;

    updateLives();

    showMessage("시간 초과! 목숨이 1개 깎였습니다.");

    if (lives <= 0) {

        endGame(false);

        return;
    }


    // 목숨이 남아있으면 봇 차례
    playerTurn = false;

    showMessage("시간 초과! 봇이 이어갑니다.");

    setTimeout(botTurn, 1000);
}


// ========================================
// 목숨 표시
// ========================================

function updateLives() {

    let hearts = "";

    for (let i = 0; i < lives; i++) {
        hearts += "❤️ ";
    }

    document.getElementById("lives").textContent =
        hearts;
}


// ========================================
// 현재 필요한 글자 표시
// ========================================

function updateNextLetter() {

    const letter =
        getRequiredLetter(currentWord);

    document.getElementById("nextLetter").textContent =
        "다음 단어는 '" + letter + "'으로 시작해야 합니다.";
}


// ========================================
// 메시지 표시
// ========================================

function showMessage(message) {

    document.getElementById("message").textContent =
        message;
}


// ========================================
// 단어 기록
// ========================================

function addWordToHistory(word) {

    const wordList =
        document.getElementById("wordList");

    const item =
        document.createElement("span");

    item.className = "word-item";

    item.textContent = word;

    wordList.appendChild(item);
}


// ========================================
// 게임 종료
// ========================================

function endGame(playerWon) {

    stopTimer();

    playerTurn = false;

    document.getElementById("gameScreen")
        .classList.add("hidden");

    document.getElementById("endScreen")
        .classList.remove("hidden");

    const result =
        document.getElementById("resultText");

    if (playerWon) {

        result.textContent =
            "🎉 승리!";

    } else {

        result.textContent =
            "😢 패배!";
    }
}


